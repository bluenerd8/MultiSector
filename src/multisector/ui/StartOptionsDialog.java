package multisector.ui;

import com.fs.starfarer.api.Global;
import com.fs.starfarer.api.campaign.CampaignUIAPI;
import com.fs.starfarer.api.campaign.InteractionDialogAPI;
import com.fs.starfarer.api.campaign.OptionPanelAPI;
import com.fs.starfarer.api.campaign.rules.MemKeys;
import com.fs.starfarer.api.campaign.rules.MemoryAPI;
import com.fs.starfarer.api.characters.FullName.Gender;
import com.fs.starfarer.api.impl.campaign.RuleBasedInteractionDialogPluginImpl;
import multisector.character.JoinCreationData;
import multisector.character.ProfileApplier;
import multisector.net.Session;

import java.util.ArrayList;
import java.util.List;

/**
 * Runs the game's real new-game starting options (starting ship, second ship,
 * and any starts that mods add through rules.csv) inside the host's world,
 * for a joining player's new character.
 *
 * Choices land in a {@link JoinCreationData} instead of a real new game.
 * Steps that only make sense for a brand-new world are stripped: the dialog
 * finishes as soon as the difficulty or tutorial question would appear, and
 * randomised and dev starts are hidden (their ships come from world-setup
 * scripts that aren't run here).
 */
public class StartOptionsDialog extends RuleBasedInteractionDialogPluginImpl {

    /** Where the game's new-game rules expect their data. */
    private static final String DATA_KEY = "$characterData";
    /** Options that end the character part of the flow: difficulty and tutorial apply to a new world. */
    private static final String[] END_OPTIONS = {"ngcNormal", "ngcEasy", "ngcTutorial", "ngcSkip"};
    /** Starts whose ships are generated by world-setup scripts we don't run, plus dev shortcuts. */
    private static final String[] HIDDEN_OPTIONS = {"ngcRandom", "ngcRandomExt1", "ngcRandomExt2", "ngcRandomExt3",
            "ngcDevStart", "ngcDevStart2"};

    private final JoinCreationData data = new JoinCreationData();
    private InteractionDialogAPI dialog;
    private final String name;
    private final Gender gender;
    private final String portrait;
    private final String downloadId;
    private final String host;
    private final int port;
    private boolean finished;

    // Set by the character chooser, opened on the next free frame (see openIfPending).
    private static StartOptionsDialog pending;

    StartOptionsDialog(String name, Gender gender, String portrait, String downloadId, String host, int port) {
        super("BeginNewGameCreation");
        this.name = name;
        this.gender = gender;
        this.portrait = portrait;
        this.downloadId = downloadId;
        this.host = host;
        this.port = port;
    }

    /** Queues the dialog; it opens once the character chooser has closed. */
    static void openSoon(StartOptionsDialog d) {
        pending = d;
    }

    static void openIfPending() {
        if (pending == null) return;
        CampaignUIAPI ui = Global.getSector().getCampaignUI();
        if (ui == null || ui.isShowingDialog() || ui.isShowingMenu()) return;
        StartOptionsDialog d = pending;
        pending = null;
        if (!ui.showInteractionDialog(d, Global.getSector().getPlayerFleet())) pending = d;
    }

    // ------------------------------------------------------------------ hooks

    /** Puts our data where the new-game rule commands look for it. */
    @Override
    public void updateMemory() {
        super.updateMemory();
        local().set(DATA_KEY, data);
    }

    @Override
    public void init(InteractionDialogAPI dialog) {
        this.dialog = dialog; // the base class keeps its own copy private
        super.init(dialog);
        tidyOptions(dialog);
    }

    /**
     * The new-game rules listen for "NewGameOptionSelected", not the
     * "DialogOptionSelected" a normal dialog fires, so send clicks the way the
     * real new-game screen does.
     */
    @Override
    public void optionSelected(String text, Object optionData) {
        if (!(optionData instanceof String)) return;
        String id = (String) optionData;
        if (FAILSAFE_LEAVE.equals(id)) {
            dialog.dismiss();
            return;
        }
        if (text != null) dialog.addOptionSelectedText(optionData);
        MemoryAPI mem = local();
        mem.set("$option", id);
        mem.expire("$option", 0);
        if (!fireBest("NewGameOptionSelected")) fireBest("DialogOptionSelected");
        tidyOptions(dialog);
    }

    @Override
    public void advance(float amount) {
        super.advance(amount);
        tidyOptions(dialog);
    }

    /** Hides starts that can't work here, and finishes when the character choices are done. */
    private void tidyOptions(InteractionDialogAPI dialog) {
        if (finished || dialog == null) return;
        OptionPanelAPI options = dialog.getOptionPanel();
        for (String id : HIDDEN_OPTIONS) {
            if (options.hasOption(id)) options.removeOption(id);
        }
        boolean end = data.isDone();
        for (String id : END_OPTIONS) end |= options.hasOption(id);
        if (end) finish(dialog);
    }

    private void finish(InteractionDialogAPI dialog) {
        finished = true;
        MemoryAPI mem = local();
        ProfileApplier.StartFlags flags = new ProfileApplier.StartFlags();
        flags.explorer = mem.getBoolean("$ngcExplorerSelected");
        flags.merc = mem.getBoolean("$ngcMercSelected");
        flags.spacer = mem.getBoolean("$ngcSpacerSelected");
        flags.addOfficer = mem.getBoolean("$ngcAddOfficer");
        cleanMemory(mem);

        Session session = Session.get();
        try {
            session.notice(ProfileApplier.applyCreation(data, name, gender, portrait, flags, downloadId));
            CharacterChooser.clearPending();
            if (host != null && !session.isActive()) {
                session.join(host, port, name);
                session.notice("Joining " + host + "...");
            }
        } catch (Exception e) {
            Global.getLogger(StartOptionsDialog.class).warn("[MultiSector] character setup failed", e);
            session.notice("couldn't set up your character: " + e.getMessage()
                    + ". Press F8 and click Choose your character to try again.");
        }
        dialog.dismiss();
    }

    /** The new-game rules leave their flags in the player fleet's memory; remove them. */
    private static void cleanMemory(MemoryAPI mem) {
        mem.unset(DATA_KEY);
        List<String> keys = new ArrayList<String>(mem.getKeys());
        for (String k : keys) {
            if (k.startsWith("$ngc") || k.startsWith("ngc")) mem.unset(k);
        }
    }

    private MemoryAPI local() {
        return getMemoryMap().get(MemKeys.LOCAL);
    }
}
